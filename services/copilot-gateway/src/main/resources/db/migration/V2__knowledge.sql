-- Enterprise knowledge base: tenant-scoped documents, their retrieval chunks, and the citations
-- an assistant turn was grounded on.
-- Portable DDL: runs on PostgreSQL and on H2 in PostgreSQL compatibility mode.

CREATE TABLE knowledge_documents (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id     VARCHAR(64)  NOT NULL,
    tenant_id  VARCHAR(64)  NOT NULL,
    app_id     VARCHAR(64)  NOT NULL,
    title      VARCHAR(300) NOT NULL,
    source     VARCHAR(1000),
    tags       VARCHAR(500),
    content    TEXT         NOT NULL,
    chunk_count INTEGER     NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP    NOT NULL
);

-- A document id is unique inside a tenant, never globally: two tenants may reuse the same id.
CREATE UNIQUE INDEX idx_knowledge_doc_key ON knowledge_documents (tenant_id, doc_id);
CREATE INDEX idx_knowledge_doc_scope ON knowledge_documents (tenant_id, app_id);

CREATE TABLE knowledge_chunks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id      VARCHAR(64) NOT NULL,
    tenant_id   VARCHAR(64) NOT NULL,
    app_id      VARCHAR(64) NOT NULL,
    chunk_index INTEGER     NOT NULL,
    -- Denormalized document title. Indexed with the body so a question phrased like the title
    -- ("退货政策是什么") still ranks the right passage, without a second table read per chunk.
    heading     VARCHAR(300) NOT NULL,
    content     TEXT        NOT NULL,
    created_at  TIMESTAMP   NOT NULL
);

CREATE INDEX idx_knowledge_chunk_scope ON knowledge_chunks (tenant_id, app_id);
CREATE INDEX idx_knowledge_chunk_doc ON knowledge_chunks (tenant_id, doc_id);

-- Sources an assistant turn cited, serialized as JSON. Restoring a thread must show the same
-- provenance the user saw while the answer streamed.
ALTER TABLE chat_messages ADD COLUMN citations TEXT;
